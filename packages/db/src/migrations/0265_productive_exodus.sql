-- DAT-009 slice 2 (E5 artifacts): the GRANT-INTENT keys on `job_artifacts`.
--
-- A `status='granted'` row is written at grant-mint time so an orphaned upload is
-- discoverable BY ITS OWN RECORD. Before this, the mint recorded nothing durable
-- (`artifact-transfer-grant.ts` never wrote a row and never recorded an operation
-- receipt), and the storage port has no list operation — so a sweeper had neither a
-- database record of what to look for nor a way to enumerate the bucket.
--
-- `job_artifacts_granted_identity_uidx` is the THIRD disjoint partial-unique over the
-- same natural key (org, job, attempt, identifier), alongside the existing `committed`
-- and `quarantined` ones. All three WHEREs are mutually exclusive, so the three row
-- kinds coexist for one natural key and none collide-updates another. It makes a
-- replayed grant request a DO-NOTHING.
--
-- `job_artifacts_granted_expiry_idx` serves the sweep lookup (granted rows whose
-- `expires_at` has passed); without it the sweep is a full table scan as artifacts grow.
--
-- Generated by `drizzle-kit generate`; the C14 idempotency guards (`IF NOT EXISTS`) were
-- hand-appended after generation so a partial-apply replay is a no-op (repo convention,
-- enforced by migration-idempotency.test.ts). Schema DDL is never hand-authored.
CREATE UNIQUE INDEX IF NOT EXISTS "job_artifacts_granted_identity_uidx" ON "job_artifacts" USING btree ("organization_id","job_id","attempt","identifier") WHERE status = 'granted';--> statement-breakpoint
CREATE INDEX IF NOT EXISTS "job_artifacts_granted_expiry_idx" ON "job_artifacts" USING btree ("expires_at") WHERE status = 'granted';
